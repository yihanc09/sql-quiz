-- Empty storage for student drafts/grades, separate from instructor SQL and data.
-- The deleted legacy quiz_answers table and its records are not restored.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS public.quiz_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    question_id integer NOT NULL CHECK (question_id BETWEEN 1 AND 5),
    sql_answer text NOT NULL DEFAULT '',
    score integer CHECK (score BETWEEN 0 AND 4),
    is_correct boolean,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, question_id),
    CHECK ((score IS NULL) = (is_correct IS NULL))
);
ALTER TABLE public.quiz_submissions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.quiz_submissions FROM PUBLIC, anon, quiz_reader;
GRANT SELECT, INSERT, UPDATE ON public.quiz_submissions TO authenticated;

DO $block$
DECLARE sequence_name text;
BEGIN
    sequence_name := pg_catalog.pg_get_serial_sequence('public.quiz_submissions', 'id');
    IF sequence_name IS NOT NULL THEN
        EXECUTE pg_catalog.format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon, quiz_reader', sequence_name::regclass);
        EXECUTE pg_catalog.format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', sequence_name::regclass);
    END IF;
END;
$block$;

DROP POLICY IF EXISTS submission_select_own ON public.quiz_submissions;
CREATE POLICY submission_select_own ON public.quiz_submissions FOR SELECT TO authenticated
USING ((SELECT auth.uid()) = user_id);
DROP POLICY IF EXISTS submission_insert_own ON public.quiz_submissions;
CREATE POLICY submission_insert_own ON public.quiz_submissions FOR INSERT TO authenticated
WITH CHECK ((SELECT auth.uid()) = user_id);
DROP POLICY IF EXISTS submission_update_own ON public.quiz_submissions;
CREATE POLICY submission_update_own ON public.quiz_submissions FOR UPDATE TO authenticated
USING ((SELECT auth.uid()) = user_id) WITH CHECK ((SELECT auth.uid()) = user_id);

CREATE OR REPLACE FUNCTION public.set_quiz_submission_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $function$
BEGIN
    NEW.updated_at = pg_catalog.now();
    RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.set_quiz_submission_updated_at() FROM PUBLIC, anon, authenticated, quiz_reader;
DROP TRIGGER IF EXISTS trg_quiz_submission_timestamp ON public.quiz_submissions;
CREATE TRIGGER trg_quiz_submission_timestamp BEFORE UPDATE ON public.quiz_submissions
FOR EACH ROW EXECUTE FUNCTION public.set_quiz_submission_updated_at();

-- The existing append-only audit function is retained after the legacy table drop.
DROP TRIGGER IF EXISTS trg_quiz_answer_audit ON public.quiz_submissions;
CREATE TRIGGER trg_quiz_answer_audit AFTER INSERT OR UPDATE ON public.quiz_submissions
FOR EACH ROW EXECUTE FUNCTION public.log_quiz_answer_change();

NOTIFY pgrst, 'reload schema';
COMMIT;
